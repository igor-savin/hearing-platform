// Assemble app/data/blogPosts.ts from per-post fragments in app/data/blog-entries/*.ts.
// Each fragment is one `"/path/": { ... },` object literal. Run after adding/editing fragments:
//   node _migration/assembleBlogPosts.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "app/data/blog-entries");
const OUT = join(ROOT, "app/data/blogPosts.ts");

const files = readdirSync(DIR).filter((f) => f.endsWith(".txt")).sort();
const blocks = files.map((f) => {
  // Defensive: writers sometimes emit &amp; for a literal & (fragments render as JSX text).
  const raw = readFileSync(join(DIR, f), "utf8").replace(/&amp;/g, "&").trimEnd();
  return raw;
});

const header = `import type { PageContent } from "../site/CaliforniaHearingSite";

// AUTO-GENERATED by _migration/assembleBlogPosts.mjs from app/data/blog-entries/*.ts.
// Do not edit by hand — edit the per-post fragment and re-run the assembler.
export const blogPosts: Record<string, PageContent> = {
`;
writeFileSync(OUT, header + blocks.join("\n\n") + "\n};\n");
console.log(`Assembled ${files.length} posts into app/data/blogPosts.ts`);
