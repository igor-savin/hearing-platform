// Assemble app/data/corePages.ts from per-page fragments in
// _migration/core-entries/*.txt (each = a keyed PageContent object literal whose
// key is the full page path). Filenames flatten the path: "/" -> "__".
//
// Usage: node _migration/assembleCorePages.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRIES = join(ROOT, "_migration/core-entries");

const files = readdirSync(ENTRIES).filter((f) => f.endsWith(".txt")).sort();
const blocks = files.map((f) => {
  let b = readFileSync(join(ENTRIES, f), "utf8").replace(/\s+$/, "");
  b = b.replace(/&amp;/g, "&");
  if (!b.endsWith(",")) b += ",";
  b = b.replace(/^\s*"/, '  "');
  return b;
});

const header =
  `import type { PageContent } from "../site/CaliforniaHearingSite";\n` +
  `import { resolveTokensDeep } from "./practice";\n\n` +
  `// AUTO-GENERATED by _migration/assembleCorePages.mjs from _migration/core-entries/*.txt.\n` +
  `// Do not edit by hand — edit the per-page fragment and re-run the assembler.\n` +
  `// These enrich service / product / tinnitus / facility pages (no BlogPosting schema:\n` +
  `// they carry no datePublished, so they get Breadcrumb + FAQ schema only).\n`;

const out =
  header +
  `const rawCorePages: Record<string, PageContent> = {\n` +
  blocks.join("\n") +
  `\n};\n\n` +
  `// Durations in the copy above are written as {{yearsInPractice}}-style tokens\n` +
  `// and filled in here, once, when the module loads. See ./practice.ts.\n` +
  `export const corePages = resolveTokensDeep(rawCorePages);\n`;

writeFileSync(join(ROOT, "app/data/corePages.ts"), out);
console.log(`Assembled corePages.ts from ${files.length} fragments.`);
