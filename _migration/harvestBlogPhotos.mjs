// Harvest each enriched blog post's REAL featured image from the legacy
// calhearing.com WordPress site (same slugs), self-host it, and write a
// slug->photo map to app/data/blogPhotos.ts. Posts without a calhearing image
// keep their on-brand SVG.
//
// Usage: node _migration/harvestBlogPhotos.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public/assets/blog-photos");
mkdirSync(OUT, { recursive: true });

const slugs = readFileSync("/tmp/chc-blog-slugs.txt", "utf8").split("\n").map((s) => s.trim()).filter(Boolean);

async function fetchText(url) {
  try {
    const r = await fetch(url, { redirect: "follow", signal: AbortSignal.timeout(20000) });
    if (!r.ok) return null;
    return await r.text();
  } catch { return null; }
}

async function download(url, dest) {
  try {
    const r = await fetch(url, { redirect: "follow", signal: AbortSignal.timeout(25000) });
    if (!r.ok) return false;
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length < 1200) return false; // skip tiny/placeholder
    writeFileSync(dest, buf);
    return true;
  } catch { return false; }
}

function extFor(url) {
  const m = url.toLowerCase().match(/\.(jpe?g|png|webp|avif)(\?|$)/);
  return m ? m[1].replace("jpeg", "jpg") : "png";
}

const map = {};
let done = 0;
const CONC = 8;
async function worker(queue) {
  while (queue.length) {
    const slug = queue.shift();
    const html = await fetchText(`https://calhearing.com/${slug}/`);
    done++;
    if (!html) continue;
    const og = (html.match(/<meta property="og:image" content="([^"]+)"/) || [])[1];
    if (!og || !/\.(jpe?g|png|webp|avif)/i.test(og)) continue;
    // skip logos/badges/gradients
    if (/logo|gradient|Ida-Label|google2|favicon|California-Hearing-Center-1\b/i.test(og)) continue;
    const ext = extFor(og);
    const dest = join(OUT, `${slug}.${ext}`);
    if (await download(og, dest)) map[`/${slug}/`] = `/assets/blog-photos/${slug}.${ext}`;
  }
}
const queue = [...slugs];
await Promise.all(Array.from({ length: CONC }, () => worker(queue)));

const header =
  `// AUTO-GENERATED by _migration/harvestBlogPhotos.mjs.\n` +
  `// Real featured images pulled from the legacy calhearing.com site (same slugs),\n` +
  `// self-hosted. Blog posts not listed here keep their generated SVG image.\n`;
const body = Object.keys(map).sort().map((k) => `  "${k}": ${JSON.stringify(map[k])},`).join("\n");
writeFileSync(join(ROOT, "app/data/blogPhotos.ts"),
  header + `export const blogPhotos: Record<string, string> = {\n${body}\n};\n`);

console.log(`Checked ${done} posts; harvested ${Object.keys(map).length} real featured images.`);
