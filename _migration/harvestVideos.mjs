// Harvest YouTube video IDs embedded on the legacy calhearing.com pages (same
// paths) for our enriched core + blog pages, and write app/data/pageVideos.ts.
// Usage: node _migration/harvestVideos.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// Collect candidate paths from corePages + blogPosts.
function pathsFrom(file) {
  try { return [...readFileSync(join(ROOT, file), "utf8").matchAll(/"(\/[^"]+\/)":\s*\{/g)].map((m) => m[1]); }
  catch { return []; }
}
const paths = [...new Set([...pathsFrom("app/data/corePages.ts"), ...pathsFrom("app/data/blogPosts.ts")])];

function extractYouTubeId(html) {
  // matches youtube.com/embed/ID, youtu.be/ID, watch?v=ID, and url-encoded variants
  const patterns = [
    /youtube(?:-nocookie)?\.com\/embed\/([A-Za-z0-9_-]{11})/,
    /youtube\.com%2Fembed%2F([A-Za-z0-9_-]{11})/,
    /youtu\.be\/([A-Za-z0-9_-]{11})/,
    /watch%3Fv%3D([A-Za-z0-9_-]{11})/,
    /[?&]v=([A-Za-z0-9_-]{11})/,
  ];
  for (const p of patterns) {
    const m = html.match(p);
    if (m && !/^(default|hqdefault)$/.test(m[1])) return m[1];
  }
  return null;
}

async function fetchText(url) {
  try {
    const r = await fetch(url, { redirect: "follow", signal: AbortSignal.timeout(20000) });
    return r.ok ? await r.text() : null;
  } catch { return null; }
}

const map = {};
let done = 0;
const CONC = 8;
async function worker(queue) {
  while (queue.length) {
    const path = queue.shift();
    const html = await fetchText(`https://calhearing.com${path}`);
    done++;
    if (!html) continue;
    const id = extractYouTubeId(html);
    if (id) map[path] = id;
  }
}
const queue = [...paths];
await Promise.all(Array.from({ length: CONC }, () => worker(queue)));

const header = `// AUTO-GENERATED by _migration/harvestVideos.mjs.\n// YouTube video IDs embedded on the matching legacy calhearing.com pages.\n`;
const body = Object.keys(map).sort().map((k) => `  "${k}": ${JSON.stringify(map[k])},`).join("\n");
writeFileSync(join(ROOT, "app/data/pageVideos.ts"), header + `export const pageVideos: Record<string, string> = {\n${body}\n};\n`);
console.log(`Checked ${done} pages; found ${Object.keys(map).length} with YouTube videos.`);
