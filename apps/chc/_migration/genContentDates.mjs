#!/usr/bin/env node
/**
 * Generate app/data/contentDates.ts — a real last-modified date per URL.
 *
 * Why not just stamp the build time: a lastmod that is provably wrong (every
 * URL changing on every deploy) is one Google learns to discount for the whole
 * site, which costs the pages where the date genuinely means something.
 *
 * Why not just omit it: omitting throws away real information. Every page here
 * DOES have a true last-edited date — it is in git, because the per-page source
 * fragments are tracked.
 *
 * Resolution order per URL:
 *   1. Blog posts use their editorial dateModified from blogPosts.ts. That is
 *      more meaningful than a commit date — it is when the article was actually
 *      revised, not when a file happened to move.
 *   2. Core and city pages use the git commit date of their own fragment.
 *   3. City x service pages (/areas-we-serve/atherton/lenire/) have no fragment
 *      of their own; they are composed from the parent city's fragment, so they
 *      inherit the parent city's date.
 *   4. Anything left (the homepage, /the-blog/, /reviews/) is rendered straight
 *      from the site component, so it takes that component's commit date.
 *
 * Re-run this after editing content fragments, then rebuild:
 *   node _migration/genContentDates.mjs
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync } from "node:fs";
import { basename } from "node:path";

const git = (args) => execFileSync("git", args, { encoding: "utf8" }).trim();
const lsFiles = (pat) => git(["ls-files", pat]).split("\n").filter(Boolean);
const lastCommitDate = (file) => git(["log", "-1", "--format=%cs", "--", file]) || null;

// --- URL -> source fragment -------------------------------------------------
const fragmentFor = new Map();
for (const f of lsFiles("app/data/blog-entries/*")) {
  fragmentFor.set(`/${basename(f).replace(/\.[^.]+$/, "")}/`, f);
}
for (const f of lsFiles("_migration/core-entries/*")) {
  const slug = basename(f).replace(/\.[^.]+$/, "").replace(/__/g, "/");
  fragmentFor.set(`/${slug}/`, f);
}
const cityFragment = new Map();
for (const f of lsFiles("_migration/city-entries/*")) {
  const slug = basename(f).replace(/\.[^.]+$/, "");
  cityFragment.set(slug, f);
  fragmentFor.set(`/areas-we-serve/${slug}/`, f);
}

// --- editorial dates for blog posts ----------------------------------------
const blogSrc = readFileSync("app/data/blogPosts.ts", "utf8");
const editorial = new Map();
for (const m of blogSrc.matchAll(/"(\/[^"]+\/)":\s*\{([\s\S]*?)\n  \},/g)) {
  const [, path, body] = m;
  const mod = body.match(/dateModified:\s*"([^"]+)"/);
  const pub = body.match(/datePublished:\s*"([^"]+)"/);
  const d = (mod && mod[1]) || (pub && pub[1]);
  if (d) editorial.set(path, d);
}

// --- every URL the sitemap will emit ---------------------------------------
const crawled = readFileSync("app/data/crawledPages.ts", "utf8");
const paths = [...crawled.matchAll(/"path":\s*"([^"]+)"/g)].map((m) => m[1]);

const componentDate = lastCommitDate("app/site/CaliforniaHearingSite.tsx");
const cache = new Map();
const dateOfFile = (f) => {
  if (!cache.has(f)) cache.set(f, lastCommitDate(f));
  return cache.get(f);
};

const out = {};
const tally = { editorial: 0, fragment: 0, parentCity: 0, component: 0 };
for (const p of paths) {
  if (editorial.has(p)) { out[p] = editorial.get(p); tally.editorial++; continue; }
  const frag = fragmentFor.get(p);
  if (frag) { out[p] = dateOfFile(frag); tally.fragment++; continue; }
  const city = p.match(/^\/areas-we-serve\/([^/]+)\/[^/]+\/$/);
  if (city && cityFragment.has(city[1])) {
    out[p] = dateOfFile(cityFragment.get(city[1])); tally.parentCity++; continue;
  }
  out[p] = componentDate; tally.component++;
}

const sorted = Object.keys(out).sort();
writeFileSync(
  "app/data/contentDates.ts",
  `// AUTO-GENERATED by _migration/genContentDates.mjs — do not edit by hand.\n` +
  `// Real last-modified date per URL, resolved from editorial metadata and git\n` +
  `// history. Re-run the generator after editing content fragments.\n` +
  `export const contentDates: Record<string, string> = {\n` +
  sorted.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join("\n") +
  `\n};\n`
);
console.log(`wrote ${sorted.length} dates`, tally);
